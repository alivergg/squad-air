#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DIST_DIR="${ROOT_DIR}/dist"
RAW_VERSION="${1:-0.1.0}"
VERSION="${RAW_VERSION#v}"
DEB_VER="${VERSION}"
RPM_VER="${VERSION//-/.}"
ARCH_VER="${VERSION//-/_}"

CLIENT_BIN="${ROOT_DIR}/target/release/squad-client"
RENDEZVOUS_BIN="${ROOT_DIR}/target/release/squad-rendezvous"
DESKTOP_FILE="${ROOT_DIR}/installer/linux/squad-air.desktop"
ICON_FILE="${ROOT_DIR}/assets/icons/icon.png"
LICENSE_FILE="${ROOT_DIR}/LICENSE"
PKGBUILD_TEMPLATE="${ROOT_DIR}/installer/linux/PKGBUILD"

for required in "${CLIENT_BIN}" "${RENDEZVOUS_BIN}" "${DESKTOP_FILE}" "${ICON_FILE}" "${LICENSE_FILE}"; do
  if [[ ! -f "${required}" ]]; then
    echo "Missing required build/asset file: ${required}" >&2
    exit 1
  fi
done

for tool in dpkg-deb rpmbuild fakeroot bsdtar zstd tar; do
  if ! command -v "${tool}" >/dev/null 2>&1; then
    echo "Missing required packaging tool: ${tool}" >&2
    exit 1
  fi
done

mkdir -p "${DIST_DIR}"
WORK_DIR="$(mktemp -d)"
trap 'rm -rf "${WORK_DIR}"' EXIT

STAGE_ROOT="${WORK_DIR}/stage"
mkdir -p \
  "${STAGE_ROOT}/usr/bin" \
  "${STAGE_ROOT}/usr/share/applications" \
  "${STAGE_ROOT}/usr/share/icons/hicolor/256x256/apps" \
  "${STAGE_ROOT}/usr/share/licenses/squad-air"

install -m 755 "${CLIENT_BIN}" "${STAGE_ROOT}/usr/bin/squad-client"
install -m 755 "${RENDEZVOUS_BIN}" "${STAGE_ROOT}/usr/bin/squad-rendezvous"
install -m 644 "${DESKTOP_FILE}" "${STAGE_ROOT}/usr/share/applications/squad-air.desktop"
install -m 644 "${ICON_FILE}" "${STAGE_ROOT}/usr/share/icons/hicolor/256x256/apps/squad-air.png"
install -m 644 "${LICENSE_FILE}" "${STAGE_ROOT}/usr/share/licenses/squad-air/LICENSE"

if command -v strip >/dev/null 2>&1; then
  strip --strip-unneeded "${STAGE_ROOT}/usr/bin/squad-client" "${STAGE_ROOT}/usr/bin/squad-rendezvous" || true
fi

# 1. Portable Linux tarballs
tar -C "${ROOT_DIR}/target/release" -czf "${DIST_DIR}/squad-client-linux-x86_64.tar.gz" squad-client
tar -C "${ROOT_DIR}/target/release" -czf "${DIST_DIR}/squad-rendezvous-linux-x86_64.tar.gz" squad-rendezvous

# 2. Debian / Ubuntu (.deb)
DEB_STAGE="${WORK_DIR}/deb"
mkdir -p "${DEB_STAGE}/DEBIAN" "${DEB_STAGE}/usr/share/doc/squad-air"
cp -a "${STAGE_ROOT}/usr/bin" "${DEB_STAGE}/usr/"
cp -a "${STAGE_ROOT}/usr/share/applications" "${DEB_STAGE}/usr/share/"
cp -a "${STAGE_ROOT}/usr/share/icons" "${DEB_STAGE}/usr/share/"
install -m 644 "${LICENSE_FILE}" "${DEB_STAGE}/usr/share/doc/squad-air/copyright"

INSTALLED_KB="$(du -sk "${DEB_STAGE}/usr" | awk '{print $1}')"
cat > "${DEB_STAGE}/DEBIAN/control" <<EOF
Package: squad-air
Version: ${DEB_VER}
Section: net
Priority: optional
Architecture: amd64
Installed-Size: ${INSTALLED_KB}
Maintainer: SquadAir Contributors <noreply@github.com>
Homepage: https://github.com/alivergg/squad-air
Depends: libc6, libasound2t64 | libasound2, libgtk-3-0t64 | libgtk-3-0, libayatana-appindicator3-1 | libappindicator3-1, libx11-6, libxkbcommon0
Description: Lightweight E2EE P2P voice chat, screen sharing, and squad messaging
 SquadAir is a low-latency peer-to-peer encrypted voice chat, hardware-accelerated
 screen sharing, and squad messaging desktop client built in Rust.
EOF
chmod 755 "${DEB_STAGE}/DEBIAN"
chmod 644 "${DEB_STAGE}/DEBIAN/control"

dpkg-deb --build --root-owner-group "${DEB_STAGE}" "${DIST_DIR}/squad-air_${DEB_VER}_amd64.deb"

# 3. Fedora / RHEL / openSUSE (.rpm)
RPM_TOP="${WORK_DIR}/rpmbuild"
mkdir -p "${RPM_TOP}"/{BUILD,RPMS,SOURCES,SPECS,SRPMS}

cat > "${RPM_TOP}/SPECS/squad-air.spec" <<EOF
%global debug_package %{nil}
%define _build_id_links none

Name:           squad-air
Version:        ${RPM_VER}
Release:        1
Summary:        Lightweight E2EE P2P voice chat, screen sharing, and squad messaging
License:        AGPL-3.0-only
URL:            https://github.com/alivergg/squad-air
AutoReqProv:    no
Requires:       alsa-lib, gtk3, libX11, libxkbcommon

%description
SquadAir is a low-latency peer-to-peer encrypted voice chat, hardware-accelerated
screen sharing, and squad messaging desktop client built in Rust.

%install
rm -rf %{buildroot}
mkdir -p %{buildroot}
cp -a "${STAGE_ROOT}/." %{buildroot}/

%files
%defattr(-,root,root,-)
/usr/bin/squad-client
/usr/bin/squad-rendezvous
/usr/share/applications/squad-air.desktop
/usr/share/icons/hicolor/256x256/apps/squad-air.png
%license /usr/share/licenses/squad-air/LICENSE
EOF

rpmbuild -bb --target x86_64 --define "_topdir ${RPM_TOP}" "${RPM_TOP}/SPECS/squad-air.spec"
cp -f "${RPM_TOP}/RPMS/x86_64/squad-air-${RPM_VER}-1.x86_64.rpm" "${DIST_DIR}/"

# 4. Arch Linux (.pkg.tar.zst + PKGBUILD)
ARCH_STAGE="${WORK_DIR}/arch"
mkdir -p "${ARCH_STAGE}"
cp -a "${STAGE_ROOT}/usr" "${ARCH_STAGE}/"

INSTALLED_BYTES="$(du -sk "${ARCH_STAGE}/usr" | awk '{print $1 * 1024}')"
BUILD_DATE="$(date -u +%s)"
cat > "${ARCH_STAGE}/.PKGINFO" <<EOF
# Generated by SquadAir package_linux.sh
pkgname = squad-air
pkgbase = squad-air
pkgver = ${ARCH_VER}-1
pkgdesc = Lightweight E2EE P2P voice chat, screen sharing, and squad messaging desktop app
url = https://github.com/alivergg/squad-air
builddate = ${BUILD_DATE}
packager = SquadAir Contributors <noreply@github.com>
size = ${INSTALLED_BYTES}
arch = x86_64
license = AGPL-3.0-only
depend = alsa-lib
depend = gtk3
depend = libx11
depend = libxkbcommon
depend = libayatana-appindicator
EOF

ARCH_OUT="${DIST_DIR}/squad-air-${ARCH_VER}-1-x86_64.pkg.tar.zst"
fakeroot -- sh -e -c "
  cd '${ARCH_STAGE}'
  chown -Rh 0:0 .PKGINFO usr
  LANG=C bsdtar -czf .MTREE --format=mtree \
    --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' \
    .PKGINFO usr
  chown 0:0 .MTREE
  LANG=C bsdtar --no-xattrs -cf - .PKGINFO .MTREE usr | zstd -c -T0 -9 > '${ARCH_OUT}'
"

sed "s/^pkgver=.*/pkgver=${ARCH_VER}/" "${PKGBUILD_TEMPLATE}" > "${DIST_DIR}/PKGBUILD"

echo "Built Linux packages in ${DIST_DIR}:"
ls -lh \
  "${DIST_DIR}/squad-air_${DEB_VER}_amd64.deb" \
  "${DIST_DIR}/squad-air-${RPM_VER}-1.x86_64.rpm" \
  "${DIST_DIR}/squad-air-${ARCH_VER}-1-x86_64.pkg.tar.zst" \
  "${DIST_DIR}/PKGBUILD" \
  "${DIST_DIR}/squad-client-linux-x86_64.tar.gz" \
  "${DIST_DIR}/squad-rendezvous-linux-x86_64.tar.gz"
